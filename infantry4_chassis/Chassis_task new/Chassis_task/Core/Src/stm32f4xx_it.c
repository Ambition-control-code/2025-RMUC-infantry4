// 在HAL_CAN_ErrorCallback中处理错误
void HAL_CAN_ErrorCallback(CAN_HandleTypeDef *hcan) {
    uint32_t error_flags = HAL_CAN_GetError(hcan);
        // 累计非致命错误次数
        static uint8_t error_count = 0;
        error_count++;
        if (error_count > 5) {  // 连续5次错误后复位
            error_count = 0;
            NVIC_SystemReset();
        }
}
